// Builds docs/ACCURACY.md from the raw evaluation results in eval/. Every number in the
// document is computed here from the result files, so the write-up cannot drift from the data.
// Each try is scored again here from the words the model returned (scripts/score.mjs), so the
// rule described in the document is the rule that was applied.
//   node scripts/report.mjs
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { rankOf } from './score.mjs';

const SETS = [
  { file: 'pnt', title: 'Philadelphia Naming Test nouns', items: 'eval/pnt.json' },
  { file: 'everyday', title: 'Everyday words (people, places, actions, feelings and times)', items: 'eval/everyday.json' },
];
const SIDES = [
  { id: 'device', label: 'On the device (Gemini Nano in Chrome)' },
  { id: 'cloud', label: 'In the cloud (Gemini through Firebase AI Logic)' },
];
const STYLES = [
  ['plain', 'A clear description'],
  ['broken', 'Broken, halting clues'],
  ['sparse', 'Two to four key words'],
];

const readJson = (f) => JSON.parse(readFileSync(f, 'utf8'));
/** The kind of each word (person, place, action, state), for test sets that record one. */
const kindOf = (itemsFile) => new Map(readJson(itemsFile).items.filter((i) => i.kind).map((i) => [i.id, i.kind]));
const KIND_LABEL = { person: 'People', place: 'Places', action: 'Actions', state: 'Feelings and times' };
const TIME_WORDS = new Set(['yesterday', 'appointment', 'tomorrow', 'weekend', 'midnight', 'birthday', 'anniversary']);
const acceptOf = (itemsFile) => new Map(readJson(itemsFile).items.map((i) => [i.id, i.accept ?? [i.target]]));

/** Result rows of one run, scored again from the words the model returned. */
function load(resultsFile, itemsFile) {
  if (!existsSync(resultsFile)) return null;
  const j = readJson(resultsFile);
  const accept = acceptOf(itemsFile);
  const rows = j.rows.filter((r) => !r.error && accept.has(r.id)).map((r) => ({ ...r, rank: rankOf(r.words, accept.get(r.id)) }));
  return { ...j, rows, failed: j.rows.filter((r) => r.error).length };
}

const pct = (rs, f) => (rs.length ? ((100 * rs.filter(f).length) / rs.length).toFixed(1) + '%' : 'n/a');
const mid = (rs, get) => { const v = rs.map(get).filter((x) => x > 0).sort((a, b) => a - b); return v.length ? v[Math.floor(v.length / 2)] : 0; };
const p90 = (rs) => { const v = rs.map((r) => r.ms).sort((a, b) => a - b); return v.length ? v[Math.floor(v.length * 0.9)] : 0; };
const secs = (ms) => (ms ? (ms / 1000).toFixed(1) + ' s' : 'n/a');
const line = (label, rs) => `| ${label} | ${rs.length} | ${pct(rs, (r) => r.rank === 0)} | ${pct(rs, (r) => r.rank >= 0 && r.rank < 3)} | ${pct(rs, (r) => r.rank >= 0)} | ${secs(mid(rs, (r) => r.firstMs ?? 0))} | ${secs(mid(rs, (r) => r.ms))} | ${secs(p90(rs))} |\n`;
const HEAD = '| Clue style | Tries | Right word first | In the first three | Among the six | First word shown | All words shown | Slowest tenth |\n|---|---|---|---|---|---|---|---|\n';

let md = `# How often does Roundabout find the word?

This page is generated by \`scripts/report.mjs\` from the raw result files in \`eval/\`. Nothing here is typed by hand.

## The test

- **Words.** The 175 picture names of the Philadelphia Naming Test, a standard naming test used in aphasia research (target list checked against the official list from Moss Rehabilitation Research Institute), plus 80 everyday words that are not simple objects.
- **Clues.** Each word has three clues, written by someone who had not seen Roundabout's prompts or code: a clear description, a broken and halting one the way a person with anomia might put it, and a sparse one of two to four key words. A clue never contains the word itself.
- **Scoring.** A try counts when an accepted answer is among the tiles offered: first, in the first three, or anywhere in the six. Close synonyms listed in the test file count (couch / sofa); related words do not. A longer name that contains the word counts (wall clock for clock). Singular and plural are treated as the same word. The rule is in \`scripts/score.mjs\`.
- **Same code as the app.** The test calls the app's own \`findWord\` function. The on-device run uses private mode, so the cloud can never answer for the device, and the cloud run uses a browser with no on-device model.
- **Times.** Answers are streamed. "First word shown" is when the first tile could appear; "all words shown" is when the answer was complete. Both are the middle value (median).

`;

const headline = [];
for (const set of SETS) {
  const total = readJson(set.items).items.length;
  md += `## ${set.title}\n\n`;
  for (const side of SIDES) {
    const res = load(`eval/results-${side.id}-${set.file}.json`, set.items);
    if (!res || !res.rows.length) { md += `**${side.label}:** not measured yet.\n\n`; continue; }
    const covered = new Set(res.rows.map((r) => r.id)).size;
    const perWord = res.rows.length / covered;
    const how = perWord > 2.5 ? 'all three clues for every word' : 'one clue per word, the three styles taking turns (the free cloud tier limits requests per minute)';
    md += `**${side.label}** — ${res.rows.length} tries on ${covered} of ${total} words${covered < total ? ' (run not complete)' : ''}: ${how}. Measured ${res.at.slice(0, 10)}.${res.failed ? ` ${res.failed} tries failed to run and are not counted.` : ''}\n\n`;
    md += HEAD;
    for (const [style, label] of STYLES) {
      const rs = res.rows.filter((r) => r.style === style);
      if (rs.length) md += line(label, rs);
    }
    md += line('**All**', res.rows) + '\n';
    headline.push(`${set.title}, ${side.id}: ${pct(res.rows, (r) => r.rank === 0)} first, ${pct(res.rows, (r) => r.rank >= 0 && r.rank < 3)} top three, ${pct(res.rows, (r) => r.rank >= 0)} in six; first word ${secs(mid(res.rows, (r) => r.firstMs ?? 0))}, all ${secs(mid(res.rows, (r) => r.ms))} (${res.rows.length} tries)`);
    const kinds = kindOf(set.items);
    if (kinds.size) {
      md += '| Kind of word | Tries | Right word first | In the first three | Among the six |\n|---|---|---|---|---|\n';
      for (const k of [...new Set(kinds.values())]) {
        const rs = res.rows.filter((r) => kinds.get(r.id) === k);
        md += `| ${KIND_LABEL[k] ?? k} | ${rs.length} | ${pct(rs, (r) => r.rank === 0)} | ${pct(rs, (r) => r.rank >= 0 && r.rank < 3)} | ${pct(rs, (r) => r.rank >= 0)} |\n`;
      }
      const t = res.rows.filter((r) => TIME_WORDS.has(r.target)), f = res.rows.filter((r) => kinds.get(r.id) === 'state' && !TIME_WORDS.has(r.target));
      if (t.length && f.length) md += `\nWithin the last row, the ${new Set(t.map((r) => r.target)).size} time words (${[...TIME_WORDS].join(', ')}) were found among the six in ${pct(t, (r) => r.rank >= 0)} of tries, and the ${new Set(f.map((r) => r.target)).size} feelings in ${pct(f, (r) => r.rank >= 0)}.\n`;
      md += '\n';
    }
    const misses = res.rows.filter((r) => r.rank < 0);
    if (misses.length) {
      md += `<details><summary>The ${misses.length} misses</summary>\n\n| Word | Clue style | Offered instead |\n|---|---|---|\n`;
      for (const m of misses) md += `| ${m.target} | ${m.style} | ${m.words.join(', ')} |\n`;
      md += '\n</details>\n\n';
    }
  }
}

// ---- the backup cloud model ----
const PACK = readJson('shared/prompts.json');
const backupRows = [];
for (const set of SETS) {
  const main = load(`eval/results-cloud-${set.file}.json`, set.items);
  const backup = load(`eval/results-cloud-${set.file}-backup.json`, set.items);
  if (!main?.rows.length || !backup?.rows.length) continue;
  const total = readJson(set.items).items.length;
  const covered = new Set(backup.rows.map((r) => r.id)).size;
  const row = (model, res) => `| ${set.title.replace(/ \(.*/, '')} | \`${model}\` | ${res.rows.length} | ${pct(res.rows, (r) => r.rank === 0)} | ${pct(res.rows, (r) => r.rank >= 0 && r.rank < 3)} | ${pct(res.rows, (r) => r.rank >= 0)} | ${secs(mid(res.rows, (r) => r.firstMs ?? 0))} | ${secs(mid(res.rows, (r) => r.ms))} | ${secs(p90(res.rows))} |\n`;
  backupRows.push({ text: row(PACK.cloudModel, main) + row(backup.model ?? PACK.cloudBackupModels[0], backup), at: backup.at, partial: covered < total ? `${covered} of ${total} words` : '', failed: backup.failed, misses: backup.rows.filter((r) => r.rank < 0), title: set.title.replace(/ \(.*/, '') });
  headline.push(`${set.title}, backup cloud model: ${pct(backup.rows, (r) => r.rank === 0)} first, ${pct(backup.rows, (r) => r.rank >= 0 && r.rank < 3)} top three, ${pct(backup.rows, (r) => r.rank >= 0)} in six; first word ${secs(mid(backup.rows, (r) => r.firstMs ?? 0))} (${backup.rows.length} tries)`);
}
if (backupRows.length) {
  md += `## The backup cloud model

A cloud request that has not started answering after a second and a half is also sent to a second cloud model, and the first answer is used (see "How a request is routed" in the README). So a cloud answer can come from the backup model, \`${PACK.cloudBackupModels[0]}\`. It was measured on the same words, one clue per word, with the same prompt. During these runs a request was never asked twice, so each row is one model alone.

| Word set | Cloud model | Tries | Right word first | In the first three | Among the six | First word shown | All words shown | Slowest tenth |
|---|---|---|---|---|---|---|---|---|
${backupRows.map((r) => r.text).join('')}
The backup was measured on ${[...new Set(backupRows.map((r) => r.at.slice(0, 10)))].join(' and ')}, at a different time of day from the main model, so the times in this table are not a like-for-like comparison of speed.${backupRows.some((r) => r.partial) ? ` Not every run was complete: ${backupRows.filter((r) => r.partial).map((r) => `${r.title}: ${r.partial}`).join('; ')}.` : ''}${backupRows.some((r) => r.failed) ? ` ${backupRows.reduce((n, r) => n + r.failed, 0)} tries failed to run and are not counted.` : ''}

`;
  for (const r of backupRows) {
    if (!r.misses.length) continue;
    md += `<details><summary>The backup model's ${r.misses.length} misses: ${r.title}</summary>\n\n| Word | Clue style | Offered instead |\n|---|---|---|\n`;
    for (const m of r.misses) md += `| ${m.target} | ${m.style} | ${m.words.join(', ')} |\n`;
    md += '\n</details>\n\n';
  }
}

// ---- how the answer format and the prompt were chosen (not test results) ----
const DEV = 'eval/dev.json';
const devRuns = [
  ['eval/results-device-dev.json', 'Short answer format, first wording'],
  ['eval/results-device-dev-a.json', 'Adds one rule: "work out the one thing all the clues point to"'],
  ['eval/results-device-dev-b.json', 'That rule plus three worked examples (the wording now in the app)'],
].map(([f, label]) => [label, existsSync(DEV) ? load(f, DEV) : null]).filter(([, r]) => r && r.rows.length);
const v1 = existsSync('eval/baseline-v1-device-pnt.json') ? load('eval/baseline-v1-device-pnt.json', 'eval/pnt.json') : null;

if (devRuns.length || v1) {
  md += `## How the answer format and the wording were chosen

These are not test results. They are the measurements that guided the build, shown so the choices can be checked.

`;
  if (v1 && v1.rows.length) {
    md += `**The first answer format was too slow on the device.** It asked for six words, each with a picture, as JSON objects. On ${v1.rows.length} tries from the test set, the on-device model took ${secs(mid(v1.rows, (r) => r.ms))} per answer (right word first ${pct(v1.rows, (r) => r.rank === 0)}). The format was changed to a plain list of words that is streamed, with pictures looked up from a table. The tables above measure that final format.\n\n`;
  }
  if (devRuns.length) {
    md += `**The wording was chosen on a separate practice set**, 30 words with clues written by the app's author (\`eval/dev.json\`; words that also appear in a test set are left out). On the device:\n\n`;
    md += '| Wording | Tries | Right word first | In the first three | Among the six |\n|---|---|---|---|---|\n';
    for (const [label, r] of devRuns) md += `| ${label} | ${r.rows.length} | ${pct(r.rows, (x) => x.rank === 0)} | ${pct(r.rows, (x) => x.rank >= 0 && x.rank < 3)} | ${pct(r.rows, (x) => x.rank >= 0)} |\n`;
    md += '\nThe test runs reported above were made after the wording was fixed. Before that, only the first answer format had been run on part of the noun test set, to measure its speed (the paragraph above).\n\n';
  }
}

md += `## What these numbers do and do not show

- They measure whether a model can find a word from a written clue. They do not measure whether Roundabout helps a person with aphasia in a real conversation; that needs testing with people who have aphasia and with speech and language therapists, which has not been done.
- The clues were written by one author imitating anomic speech. Real clues will be more varied.
- Cloud times include the network from the United Arab Emirates. On-device times are from one laptop (Windows, RTX 4050 with 6 GB) and depend on the hardware.
- Scoring is strict about the form of a word: *complaint* for *complain*, or *relief* for *relieved*, counts as a miss. Several misses on the everyday words are of this kind; the lists of misses above show what was offered instead.
- The on-device model finds objects, places and times well, and actions and feelings poorly. The app acts on that: when the person taps "something you do" or "a feeling", the cloud is asked first (unless private mode is on or there is no connection), and "None of these" always asks the cloud.
- The cloud runs shared the laptop with the on-device test for part of the time, which slowed some cloud requests. Cloud times here are on the slow side.
- Very short clues are also hard for the small on-device model. In the app, a clue of three words or fewer answered on the device also gets ideas from the cloud (unless private mode is on or there is no connection).
`;

mkdirSync('docs', { recursive: true });
writeFileSync('docs/ACCURACY.md', md);
console.log(headline.join('\n'));
