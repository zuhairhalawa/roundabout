// Builds docs/ACCURACY.md from the raw evaluation results in eval/. Every number in the
// document is computed here from the result files, so the write-up cannot drift from the data.
//   node scripts/report.mjs
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const SETS = [
  { file: 'pnt', title: 'Philadelphia Naming Test nouns', items: 'eval/pnt.json' },
  { file: 'everyday', title: 'Everyday words (people, places, actions, feelings and times)', items: 'eval/everyday.json' },
];
const SIDES = [
  { id: 'device', label: 'On the device (Gemini Nano in Chrome)' },
  { id: 'cloud', label: 'In the cloud (Gemini through Firebase AI Logic)' },
];
const STYLES = [
  ['plain', 'A clear description'],
  ['broken', 'Broken, halting clues'],
  ['sparse', 'Two to four key words'],
];

const load = (side, set) => {
  const f = `eval/results-${side}-${set}.json`;
  if (!existsSync(f)) return null;
  const j = JSON.parse(readFileSync(f, 'utf8'));
  return { ...j, rows: j.rows.filter((r) => !r.error) };
};
const pct = (rs, f) => (rs.length ? ((100 * rs.filter(f).length) / rs.length).toFixed(1) + '%' : 'n/a');
const median = (rs) => { const ms = rs.map((r) => r.ms).sort((a, b) => a - b); return ms.length ? ms[Math.floor(ms.length / 2)] : 0; };
const p90 = (rs) => { const ms = rs.map((r) => r.ms).sort((a, b) => a - b); return ms.length ? ms[Math.floor(ms.length * 0.9)] : 0; };
const secs = (ms) => (ms / 1000).toFixed(1) + ' s';

let md = `# How often does Roundabout find the word?

This page is generated by \`scripts/report.mjs\` from the raw result files in \`eval/\`. Nothing here is typed by hand.

## The test

- **Words.** The 175 picture names of the Philadelphia Naming Test, a standard naming test used in aphasia research (target list checked against the official list from Moss Rehabilitation Research Institute), plus 80 everyday words that are not simple objects.
- **Clues.** Each word has three clues, written by someone who had not seen Roundabout's prompts or code: a clear description, a broken and halting one the way a person with anomia might put it, and a sparse one of two to four key words. A clue never contains the word itself.
- **Scoring.** A try counts when an accepted answer is among the tiles offered: first, in the first three, or anywhere in the six. Close synonyms listed in the test file count (couch / sofa); related words do not. Singular and plural are treated as the same word.
- **Same code as the app.** The test calls the app's own \`findWord\` function. The on-device run uses private mode, so the cloud can never answer for the device.

`;

for (const set of SETS) {
  const total = JSON.parse(readFileSync(set.items, 'utf8')).items.length;
  md += `## ${set.title}\n\n`;
  let any = false;
  for (const side of SIDES) {
    const res = load(side.id, set.file);
    if (!res || !res.rows.length) { md += `**${side.label}:** not measured yet.\n\n`; continue; }
    any = true;
    const covered = new Set(res.rows.map((r) => r.id)).size;
    md += `**${side.label}** — ${res.rows.length} tries on ${covered} of ${total} words${covered < total ? ' (run not complete)' : ''}, measured ${res.at.slice(0, 10)}.\n\n`;
    md += '| Clue style | Tries | Right word first | In the first three | Among the six | Typical time | Slowest tenth |\n|---|---|---|---|---|---|---|\n';
    for (const [style, label] of STYLES) {
      const rs = res.rows.filter((r) => r.style === style);
      if (!rs.length) continue;
      md += `| ${label} | ${rs.length} | ${pct(rs, (r) => r.rank === 0)} | ${pct(rs, (r) => r.rank >= 0 && r.rank < 3)} | ${pct(rs, (r) => r.rank >= 0)} | ${secs(median(rs))} | ${secs(p90(rs))} |\n`;
    }
    const rs = res.rows;
    md += `| **All** | ${rs.length} | ${pct(rs, (r) => r.rank === 0)} | ${pct(rs, (r) => r.rank >= 0 && r.rank < 3)} | ${pct(rs, (r) => r.rank >= 0)} | ${secs(median(rs))} | ${secs(p90(rs))} |\n\n`;
    const misses = rs.filter((r) => r.rank < 0);
    if (misses.length) {
      md += `<details><summary>The ${misses.length} misses</summary>\n\n| Word | Clue style | Offered instead |\n|---|---|---|\n`;
      for (const m of misses) md += `| ${m.target} | ${m.style} | ${m.words.join(', ')} |\n`;
      md += '\n</details>\n\n';
    }
  }
  if (!any) md += '\n';
}

md += `## What these numbers do and do not show

- They measure whether a model can find a word from a written clue. They do not measure whether Roundabout helps a person with aphasia in a real conversation; that needs testing with people who have aphasia and with speech and language therapists, which has not been done.
- The clues were written by one author imitating anomic speech. Real clues will be more varied.
- Cloud times include the network from the United Arab Emirates. On-device times are from one laptop (Windows, RTX 4050 with 6 GB) and depend on the hardware.
`;

mkdirSync('docs', { recursive: true });
writeFileSync('docs/ACCURACY.md', md);
